export function fieldVisible(field, config) {
  if (!field.showWhen) return true
  return Object.entries(field.showWhen).every(([k, v]) => config[k] === v)
}

function coerceNumberList(current, key, value) {
  const prev = current?.[key]
  const keepList = Array.isArray(prev) || key === 'chatBackoffRetrySec'
  if (!keepList || typeof value !== 'string') return value
  const parts = value.split(/[,，\s]+/).map((s) => s.trim()).filter(Boolean)
  if (!parts.length || !parts.every((p) => /^-?\d+(\.\d+)?$/.test(p))) return value
  return parts.map(Number).filter((n) => n > 0)
}

const TTS_JSON_KEYS = new Set([
  'chatTtsExtra',
  'chatTtsDoubaoExtra',
  'chatTtsQwenExtra',
  'chatTtsOpenaiExtra',
])

function coerceJsonObject(key, value) {
  if (!TTS_JSON_KEYS.has(key)) return value
  if (value && typeof value === 'object' && !Array.isArray(value)) return value
  if (typeof value !== 'string') return {}
  const s = value.trim()
  if (!s) return {}
  try {
    const parsed = JSON.parse(s)
    return parsed && typeof parsed === 'object' && !Array.isArray(parsed) ? parsed : {}
  } catch {
    return value
  }
}

export function mergeConfigPatch(current, patch) {
  const next = { ...current }
  for (const [key, value] of Object.entries(patch)) {
    if (value === undefined) continue
    next[key] = coerceJsonObject(key, coerceNumberList(current, key, value))
  }
  return next
}
